# Стихийные преимущества (+25% урона)
ELEMENT_ADVANTAGES = {
    "Огонь": ["Био", "Лед"],
    "Био": ["Электро", "Земля"],
    "Электро": ["Вода", "Воздух"],
    "Вода": ["Огонь", "Земля"],
    "Лед": ["Воздух", "Био"],
    "Воздух": ["Яд", "Био"],
    "Земля": ["Электро", "Огонь", "Яд"],
    "Яд": ["Био", "Вода"],
    "Тьма": ["Космос"],
    "Космос": ["Тьма"],
    "Металл": ["Лед", "Яд"],
}

def get_element_multiplier(atk_elem: str, def_elem: str) -> float:
    """Расчет множителя урона: 1.25 при преимуществе, 0.8 при слабости, иначе 1.0"""
    if def_elem in ELEMENT_ADVANTAGES.get(atk_elem, []):
        return 1.25
    if atk_elem in ELEMENT_ADVANTAGES.get(def_elem, []):
        return 0.80
    return 1.0

def get_monster_info(name: str) -> dict:
    return MONSTERS.get(name, MONSTERS["Вольтфокс"])
